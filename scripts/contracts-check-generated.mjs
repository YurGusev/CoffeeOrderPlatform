#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const root = resolve(import.meta.dirname, '..');
const generatedRoot = resolve(root, 'packages/generated');
const browserOperationsPath = resolve(root, 'apps/edge-gateway/src/client-operations.gen.ts');
const generatedSources = ['client-v1/src', 'internal-v1/src', 'edge-auth-v1/src'].map((path) => resolve(generatedRoot, path));

async function digest(path) {
  const hash = createHash('sha256');
  async function walk(directory) {
    for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
      const child = resolve(directory, entry.name);
      if (entry.isDirectory()) await walk(child);
      else {
        hash.update(child.slice(generatedRoot.length));
        hash.update(await readFile(child));
      }
    }
  }
  await walk(path);
  return hash.digest('hex');
}

const before = createHash('sha256');
for (const path of generatedSources) before.update(await digest(path));
before.update('apps/edge-gateway/src/client-operations.gen.ts');
before.update(await readFile(browserOperationsPath));
const result = spawnSync(process.execPath, ['scripts/contracts-generate.mjs'], { cwd: root, stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status ?? 1);
const after = createHash('sha256');
for (const path of generatedSources) after.update(await digest(path));
after.update('apps/edge-gateway/src/client-operations.gen.ts');
after.update(await readFile(browserOperationsPath));
const beforeHash = before.digest('hex');
const afterHash = after.digest('hex');
if (beforeHash !== afterHash) throw new Error(`generated drift: ${beforeHash} != ${afterHash}`);
console.log(`contracts generated byte-identically: ${afterHash}`);
